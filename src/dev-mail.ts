/**
 * Чисте маскування для dev-консолі: логи часто збираються централізовано, тому
 * код підтвердження чи токен скидання не можна друкувати навіть локально.
 */
export function redactDevMail(text: string): string {
  return text
    // `amp;` — для випадку, якщо в консоль потрапить уже HTML-екранований лист.
    .replace(/([?&](?:amp;)?(?:token|code)=)[^\s&]+/gi, '$1***')
    .replace(/\b\d{6}\b/g, '******');
}
